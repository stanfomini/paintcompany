    /**
     * Run the database seeds.
     *
     * Seeds terms & conditions, privacy policy, referral terms,
     * and default estimate terms on the CompanySetting singleton.
     */
    public function run(): void
    {
        $settings = CompanySetting::getInstance();

        $companyName = config('app.name', 'Our Company');
        $date = now()->format('F j, Y');

        $updated = [];

        if (empty($settings->terms_and_conditions)) {
            $settings->terms_and_conditions = $this->getTermsAndConditions($companyName, $date);
            $updated[] = 'terms_and_conditions';
        }

        if (empty($settings->privacy_policy)) {
            $settings->privacy_policy = $this->getPrivacyPolicy($companyName, $date);
            $updated[] = 'privacy_policy';
        }

        if (empty($settings->referral_terms)) {
            $settings->referral_terms = $this->getReferralTerms($companyName, $date);
            $updated[] = 'referral_terms';
        }

        if (empty($settings->default_terms_and_conditions)) {
            $settings->default_terms_and_conditions = $this->getDefaultTerms($companyName);
            $updated[] = 'default_terms_and_conditions';
        }

        if (! empty($updated)) {
            $settings->save();
            $this->command->info('Legal documents seeded: '.implode(', ', $updated));
        } else {
            $this->command->info('Legal documents already populated. No changes made.');
        }
    }

